IF DB_ID(N'OOAD_Bakery') IS NULL CREATE DATABASE OOAD_Bakery;
GO
USE OOAD_Bakery;
GO
CREATE TABLE NhanVien (MaNV INT IDENTITY PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, SDT VARCHAR(15), Email VARCHAR(120), DiaChi NVARCHAR(255));
CREATE TABLE KhachHang (MaKH INT IDENTITY PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, SDT VARCHAR(15), Email VARCHAR(120), DiaChi NVARCHAR(255));
CREATE TABLE NhaCungCap (MaNCC INT IDENTITY PRIMARY KEY, TenNCC NVARCHAR(150) NOT NULL, SDT VARCHAR(15), Email VARCHAR(120), DiaChi NVARCHAR(255));
CREATE TABLE TaiKhoan (
 MaTK INT IDENTITY PRIMARY KEY, TenTK NVARCHAR(60) NOT NULL UNIQUE,
 MatKhau NVARCHAR(255) NOT NULL, VaiTro NVARCHAR(30) NOT NULL,
 TT NVARCHAR(30) NOT NULL DEFAULT N'Hoạt động', NgayTao DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 MaNV INT NOT NULL UNIQUE, CONSTRAINT FK_TK_NV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
 CONSTRAINT CK_TK_Role CHECK (VaiTro IN (N'Admin',N'Quản lý',N'Nhân viên'))
);
CREATE TABLE DanhMuc (
 MaDM INT IDENTITY PRIMARY KEY, TenDM NVARCHAR(100) NOT NULL, MoTa NVARCHAR(255),
 TT NVARCHAR(30) NOT NULL DEFAULT N'Đang dùng', CONSTRAINT UQ_DM_Ten UNIQUE (TenDM)
);
CREATE TABLE SanPham (
 MaSP INT IDENTITY PRIMARY KEY, TenSP NVARCHAR(150) NOT NULL,
 MaDM INT NOT NULL REFERENCES DanhMuc(MaDM), HinhAnh NVARCHAR(255),
 ThanhPhan NVARCHAR(MAX), MoTa NVARCHAR(MAX), TrongLuong DECIMAL(10,2),
 GiaBan DECIMAL(18,2) NOT NULL DEFAULT 0, HSD INT, NguongTon INT NOT NULL DEFAULT 0,
 TT NVARCHAR(30) NOT NULL DEFAULT N'Đang bán',
 CONSTRAINT CK_SP_Gia CHECK (GiaBan >= 0), CONSTRAINT CK_SP_TrongLuong CHECK (TrongLuong IS NULL OR TrongLuong > 0),
 CONSTRAINT CK_SP_HSD CHECK (HSD IS NULL OR HSD > 0), CONSTRAINT CK_SP_Nguong CHECK (NguongTon >= 0)
);
CREATE TABLE PhieuNhapKho (
 MaPN INT IDENTITY PRIMARY KEY, NgayNhap DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 MaNCC INT NOT NULL REFERENCES NhaCungCap(MaNCC), MaNV INT NOT NULL REFERENCES NhanVien(MaNV),
 TongTien DECIMAL(18,2) NOT NULL DEFAULT 0, TT NVARCHAR(30) NOT NULL DEFAULT N'Bản nháp',
 CONSTRAINT CK_PN_Tong CHECK (TongTien >= 0)
);
CREATE TABLE ChiTietPhieuNhap (
 MaCTPN INT IDENTITY PRIMARY KEY, MaPN INT NOT NULL REFERENCES PhieuNhapKho(MaPN),
 MaSP INT NOT NULL REFERENCES SanPham(MaSP), SLNhap INT NOT NULL,
 GiaVon DECIMAL(18,2) NOT NULL, ThanhTien AS CONVERT(DECIMAL(18,2), SLNhap * GiaVon) PERSISTED,
 CONSTRAINT CK_CTPN_SL CHECK (SLNhap > 0), CONSTRAINT CK_CTPN_Gia CHECK (GiaVon >= 0),
 CONSTRAINT UQ_CTPN_SP UNIQUE(MaCTPN,MaSP)
);
CREATE TABLE LoHang (
 MaLo INT IDENTITY PRIMARY KEY, MaCTPN INT NOT NULL, MaSP INT NOT NULL,
 NgayNhap DATETIME2 NOT NULL, NgayHetHan DATETIME2, SLNhap INT NOT NULL,
 SLCon INT NOT NULL, GiaVon DECIMAL(18,2) NOT NULL,
 CONSTRAINT FK_Lo_CTPN_SP FOREIGN KEY (MaCTPN,MaSP) REFERENCES ChiTietPhieuNhap(MaCTPN,MaSP),
 CONSTRAINT CK_Lo_SL CHECK (SLNhap > 0 AND SLCon >= 0 AND SLCon <= SLNhap),
 CONSTRAINT CK_Lo_Gia CHECK (GiaVon >= 0),
 CONSTRAINT CK_Lo_Han CHECK (NgayHetHan IS NULL OR NgayHetHan >= NgayNhap)
);
CREATE TABLE CauHinhGiaBan (
 MaCH INT IDENTITY PRIMARY KEY, MaSP INT NOT NULL REFERENCES SanPham(MaSP),
 TyLeLN DECIMAL(8,4) NOT NULL, NgayAD DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 MaNV INT NOT NULL REFERENCES NhanVien(MaNV), CONSTRAINT CK_CH_TyLe CHECK (TyLeLN >= 0)
);
CREATE TABLE DonHang (
 MaDH INT IDENTITY PRIMARY KEY, MaKH INT NOT NULL REFERENCES KhachHang(MaKH),
 MaNV INT NOT NULL REFERENCES NhanVien(MaNV), NgayDat DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 NgayGiao DATETIME2, TongTien DECIMAL(18,2) NOT NULL DEFAULT 0,
 PTTT NVARCHAR(40), TTThanhToan NVARCHAR(30) NOT NULL DEFAULT N'Chưa thanh toán',
 TTDon NVARCHAR(30) NOT NULL DEFAULT N'Mới', LyDoHuy NVARCHAR(255), GhiChu NVARCHAR(255),
 CONSTRAINT CK_DH_Tong CHECK(TongTien >= 0)
);
CREATE TABLE ChiTietDonHang (
 MaCTDH INT IDENTITY PRIMARY KEY, MaDH INT NOT NULL REFERENCES DonHang(MaDH),
 MaSP INT NOT NULL REFERENCES SanPham(MaSP), SL INT NOT NULL, DonGia DECIMAL(18,2) NOT NULL,
 ThanhTien AS CONVERT(DECIMAL(18,2), SL * DonGia) PERSISTED,
 CONSTRAINT CK_CTDH_SL CHECK (SL > 0), CONSTRAINT CK_CTDH_Gia CHECK (DonGia >= 0)
);
CREATE TABLE YeuCauHoanTien (
 MaYC INT IDENTITY PRIMARY KEY, MaDH INT NOT NULL UNIQUE REFERENCES DonHang(MaDH),
 SoTien DECIMAL(18,2) NOT NULL, PTNhanTien NVARCHAR(40),
 NgayYC DATETIME2 NOT NULL DEFAULT SYSDATETIME(), TT NVARCHAR(30) NOT NULL DEFAULT N'Chờ duyệt',
 CONSTRAINT CK_YC_SoTien CHECK (SoTien > 0)
);
CREATE TABLE GiaoNhan (
 MaGN INT IDENTITY PRIMARY KEY, MaDH INT NOT NULL UNIQUE REFERENCES DonHang(MaDH),
 NguoiNhan NVARCHAR(100) NOT NULL, SDTNhan VARCHAR(15), DiaChiNhan NVARCHAR(255),
 Phuong NVARCHAR(100), DonViVC NVARCHAR(100), NguoiGiao NVARCHAR(100),
 PhiGiao DECIMAL(18,2) NOT NULL DEFAULT 0, TienCOD DECIMAL(18,2) NOT NULL DEFAULT 0,
 TTGiao NVARCHAR(30) NOT NULL DEFAULT N'Chờ giao', LyDoThatBai NVARCHAR(255),
 CONSTRAINT CK_GN_Phi CHECK (PhiGiao >= 0 AND TienCOD >= 0)
);
CREATE TABLE LichSuGiaoNhan (
 MaLS INT IDENTITY PRIMARY KEY, MaGN INT NOT NULL REFERENCES GiaoNhan(MaGN),
 TTTruoc NVARCHAR(30), TTSau NVARCHAR(30) NOT NULL, ThoiGian DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 MaNV INT NOT NULL REFERENCES NhanVien(MaNV), GhiChu NVARCHAR(255)
);
CREATE TABLE PhanBoXuatLo (
 MaPB INT IDENTITY PRIMARY KEY, MaCTDH INT NOT NULL REFERENCES ChiTietDonHang(MaCTDH),
 MaLo INT NOT NULL REFERENCES LoHang(MaLo), SLXuat INT NOT NULL,
 NgayXuat DATETIME2 NOT NULL DEFAULT SYSDATETIME(), CONSTRAINT CK_PB_SL CHECK (SLXuat > 0)
);
GO
CREATE INDEX IX_SP_DM ON SanPham(MaDM);
CREATE INDEX IX_Lo_SP_FIFO ON LoHang(MaSP,NgayNhap,MaLo) INCLUDE (SLCon,NgayHetHan);
CREATE INDEX IX_CTDH_DH ON ChiTietDonHang(MaDH);
CREATE INDEX IX_PB_Lo ON PhanBoXuatLo(MaLo);
CREATE INDEX IX_PB_CT ON PhanBoXuatLo(MaCTDH);
GO
